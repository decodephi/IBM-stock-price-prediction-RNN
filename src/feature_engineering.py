import os
import sys
import yaml

from logger import logger
from exception import CustomException
import pandas as pd


class FeatureEngineering:

    def __init__(self, df):

        self.df = df

        with open("config/config.yaml", "r") as file:
            config = yaml.safe_load(file)

        self.output_path = config["feature_engineering"]["featured_data_path"]

    def engineer_features(self):

        try:

            logger.info("Starting Feature Engineering...")

            self.df["Year"] = self.df["Date"].dt.year
            self.df["Month"] = self.df["Date"].dt.month
            self.df["Quarter"] = self.df["Date"].dt.quarter
            self.df["Day"] = self.df["Date"].dt.day
            self.df["DayOfWeek"] = self.df["Date"].dt.dayofweek

            logger.info("Calendar features created successfully.")
            ##########################################################
            logger.info("Creating lag features...")

            self.df["Lag_1"] = self.df["Close"].shift(1)
            self.df["Lag_7"] = self.df["Close"].shift(7)
            self.df["Lag_30"] = self.df["Close"].shift(30)

            logger.info("Lag features created successfully.")
            
            ######################################################
            logger.info("Creating rolling statistics features...")

            # Rolling Mean
            self.df["Rolling_Mean_7"] = self.df["Close"].rolling(window=7).mean()
            self.df["Rolling_Mean_30"] = self.df["Close"].rolling(window=30).mean()

            # Rolling Standard Deviation (Volatility)
            self.df["Rolling_STD_7"] = self.df["Close"].rolling(window=7).std()
            self.df["Rolling_STD_30"] = self.df["Close"].rolling(window=30).std()

            logger.info("Rolling statistics created successfully.")
            
            ##############################################################################
            
            logger.info("Removing NaN values generated by rolling statistics.")

            self.df.dropna(inplace=True)
            self.df.reset_index(drop=True, inplace=True)

            logger.info("Rolling statistics preprocessing completed.")
            
            #####################################################################################
            logger.info("Creating financial indicators...")


            # SMA (Simple Moving Average)

            self.df["SMA_20"] = self.df["Close"].rolling(window=20).mean()
            self.df["SMA_50"] = self.df["Close"].rolling(window=50).mean()


            # EMA (Exponential Moving Average)

            self.df["EMA_20"] = self.df["Close"].ewm(span=20, adjust=False).mean()


            # RSI (Relative Strength Index)

            delta = self.df["Close"].diff()

            gain = delta.clip(lower=0)
            loss = -delta.clip(upper=0)

            avg_gain = gain.rolling(window=14).mean()
            avg_loss = loss.rolling(window=14).mean()

            rs = avg_gain / avg_loss

            self.df["RSI_14"] = 100 - (100 / (1 + rs))


            # MACD

            ema12 = self.df["Close"].ewm(span=12, adjust=False).mean()
            ema26 = self.df["Close"].ewm(span=26, adjust=False).mean()

            self.df["MACD"] = ema12 - ema26

            self.df["MACD_Signal"] = (
            self.df["MACD"]
            .ewm(span=9, adjust=False)
            .mean()
           )

            self.df["MACD_Histogram"] = (
                self.df["MACD"] - self.df["MACD_Signal"]
            )


            # Bollinger Bands

            rolling_mean = self.df["Close"].rolling(window=20).mean()
            rolling_std = self.df["Close"].rolling(window=20).std()

            self.df["BB_Upper"] = rolling_mean + (2 * rolling_std)
            self.df["BB_Lower"] = rolling_mean - (2 * rolling_std)
            self.df["BB_Width"] = self.df["BB_Upper"] - self.df["BB_Lower"]


            # ATR (Average True Range)

            high_low = self.df["High"] - self.df["Low"]

            high_close = (
                self.df["High"] - self.df["Close"].shift(1)
            ).abs()

            low_close = (
                self.df["Low"] - self.df["Close"].shift(1)
            ).abs()

            true_range = pd.concat(
                [high_low, high_close, low_close],
                axis=1
            ).max(axis=1)

            self.df["ATR_14"] = (
                true_range
                .rolling(window=14)
                .mean()
            )

            self.df["Momentum_10"] = (
                self.df["Close"] -
                self.df["Close"].shift(10)
            )

            logger.info("Financial indicators created successfully.")

            # Remove NaN rows generated by rolling calculations
            self.df.dropna(inplace=True)
            self.df.reset_index(drop=True, inplace=True)

            logger.info("Financial indicator preprocessing completed.")

            os.makedirs(
                os.path.dirname(self.output_path),
                exist_ok=True
            )

            self.df.to_csv(
                self.output_path,
                index=False
            )

            logger.info(
                f"Feature dataset saved to {self.output_path}"
            )

            return self.df

        except Exception as e:

            logger.error(e)

            raise CustomException(e, sys)